#!/usr/bin/env python3
"""Generate the depth-2 hybrid study on liquid water.

The question: does a Mamba + attention stack fit better than either pure stack,
and better than no mixer at all?  Every arm is the configuration that produced
the recorded H100 water runs (``results/water_h100_partial/configs``), with only
the changes below.  Nothing else differs between arms.

Arms (``num_layers: 2``):

    identity   [identity,  identity ]   no cross-shell communication (control)
    attention  [attention, attention]
    mamba      [mamba,     mamba    ]
    hybrid     [mamba,     attention]   anchored_schedule(2, 1)

Changes from the recorded H100 runs, and why:

* ``num_layers: 2`` -- a schedule needs at least two layers; at depth one the
  "hybrid" cannot exist.
* ``gate_norm: rms`` in every arm -- the converged CsPbI3 Mamba run saturated
  its gate (|pre-activation| ~ 4768), collapsing the mixer's contribution.
  Identical in every arm, so the comparison stays controlled.
* ``batch_size: 2`` -- each 768-atom frame carries 2304 force labels, and at
  batch 8 the 168 training frames give only 21 optimiser steps per epoch.  Batch
  2 gives 4x the steps for the same compute per epoch.
* ``epochs: 50`` -- 4200 optimiser steps, twice the entire 100-epoch schedule of
  the recorded runs, which were stopped while still improving.
* ``seed`` varies per replicate, ``split_seed`` is fixed: every replicate and
  every arm is scored on the same validation frames, and the seed scatter is
  initialisation noise alone.

* ``mixer_checkpoint: true`` -- activation checkpointing of the mixer; changes
  memory, not the function.

``mixing_fraction`` and ``branch_fraction`` are logged every five epochs
(``gate_diagnostic_every``); report them next to the errors.  Model settings
not named here keep the architecture-v12 defaults.

    python3 training/water_hybrid/make_configs.py          # writes the YAMLs
    cd training/water_hybrid && python3 ../../train.py --config config_hybrid_s1.yaml
"""

from __future__ import annotations

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCE = REPO / "results" / "water_h100_partial" / "configs" / "h100_mamba.yaml"

ARMS = {
    "identity": ["identity", "identity"],
    "attention": ["attention", "attention"],
    "mamba": ["mamba", "mamba"],
    "hybrid": ["mamba", "attention"],
}
SEEDS = (1, 2, 3)
SPLIT_SEED = 42  # the split of the recorded H100 runs


def configuration(arm: str, seed: int) -> dict:
    config = yaml.safe_load(SOURCE.read_text())
    config.pop("mixer_type", None)
    config.update(
        train_file="../../results/water_h100_partial/water_bulk.xyz",
        model_save_path=f"./model_{arm}_s{seed}.pt",
        last_model_save_path=f"./model_{arm}_s{seed}_last.pt",
        num_layers=2,
        mixer_schedule=ARMS[arm],
        gate_norm="rms",
        batch_size=2,
        epochs=50,
        seed=seed,
        split_seed=SPLIT_SEED,
        gate_diagnostic_every=5,
        # Cost only: recompute the mixer in reverse mode.  Measured 37% lower
        # peak memory per force-training step at identical gradients.
        mixer_checkpoint=True,
    )
    return config


def main() -> None:
    header = (
        "# Generated by make_configs.py -- edit that file, not this one.\n"
        "# Depth-2 hybrid study on liquid water; see make_configs.py for the design.\n"
    )
    for arm in ARMS:
        for seed in SEEDS:
            path = HERE / f"config_{arm}_s{seed}.yaml"
            path.write_text(header + yaml.safe_dump(configuration(arm, seed), sort_keys=False))
            print(path.relative_to(REPO))


if __name__ == "__main__":
    main()
